async function seed() {
  console.log('Connecting to MongoDB Atlas...');
  await mongoose.connect(process.env.MONGO_URI, { serverSelectionTimeoutMS: 10000 });
  console.log('Connected! Seeding tours across 6 sections...');

  let inserted = 0;
  let updated = 0;

  for (const tourData of SEED_TOURS) {
    const existing = await Tour.findOne({ title: tourData.title });
    if (existing) {
      existing.section = tourData.section;
      existing.category = tourData.category;
      existing.location = tourData.location;
      existing.duration = tourData.duration;
      existing.vehicle = tourData.vehicle;
      existing.guide = tourData.guide;
      existing.capacity = tourData.capacity;
      existing.price = tourData.price;
      existing.currency = tourData.currency;
      existing.rating = tourData.rating;
      existing.images = tourData.images;
      existing.description = tourData.description;
      existing.highlights = tourData.highlights;
      existing.isActive = true;
      await existing.save();
      updated++;
    } else {
      await Tour.create(tourData);
      inserted++;
    }
  }

  const allTours = await Tour.find({});
  console.log(`\nDone! Inserted: ${inserted}, Updated: ${updated}. Total in DB now: ${allTours.length}`);

  // Summary per section
  const sectionCounts = {};
  allTours.forEach(t => {
    const sec = t.section || 'unassigned';
    sectionCounts[sec] = (sectionCounts[sec] || 0) + 1;
  });
  console.log('\nFinal DB distribution by section:', sectionCounts);

  await mongoose.disconnect();
  console.log('MongoDB connection closed.');
}

seed().catch(err => {
  console.error('Seeding error:', err);
  process.exit(1);
});
